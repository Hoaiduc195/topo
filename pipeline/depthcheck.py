"""How deep a map goes: the depth check every map has to pass, whichever model drew it.

usage: python3 -I pipeline/depthcheck.py MAP_DIR [--repo CHECKOUT] [--limit 20]

A map's depth is chosen when it starts ("depth" in its topo.config.json: overview, standard, deep, a
depth this machine defines, or one kept in full; standard when unset). The depths are data: depths.json
holds the built-in ones and depths.py describes every field. The floors below are standard's. An
overview needs no symbol boxes and 3 excerpts an area, and its file boxes (or a box inside each) must be
connected; deep needs a symbol box for 65% of every area's public definitions, with no cap, and 15
excerpts an area. The precision rules (every symbol box cites its line) hold at every depth.

Four measures, each with a floor:

  public definitions  the classes, functions and types the code exports, and the public methods of its
                      public classes, that have a box (an f:<path>#<name> or f:<path>#<Class>.<method>
                      id). When they fit in the map (no more than half the boxes its code areas can hold,
                      at 150 boxes an area), at least 65% must have one. A larger map is mapped at the
                      depth of its core, so then the report only lists the files with the most left out.
  connections         symbol boxes (f:<path>#<name>) with at least one connection: 80% or more. A box with
                      none says what a function is but not what it does in the system.
  symbol boxes        per area: at least 65% of its public definitions, counting at most 75 of them, so
                      an area of a large codebase still goes to symbol level. Every symbol box cites a
                      line (path:line), or the line can't be checked.
  code excerpts       verbatim excerpts: at least 10 an area (the briefs ask for 10 to 15), or one per
                      symbol box when there are fewer.

Tests, docs, examples, vendored folders and generated code (by its name, a generated/ folder, or a
"generated" or "do not edit" marker in its first lines) are left out, and so are TypeScript types. A
file that defines only one or two public names (a component per file, say) counts as mapped at symbol
level when it has its own file box. Languages read: Python (parsed, with methods),
Go (exported names, and the exported methods of exported types), JavaScript and TypeScript (exports),
Rust (pub items), Java, Kotlin, C#, Swift and Ruby (top-level types). Other languages are not counted.
"""
import argparse
import ast
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from init import VENDORED  # noqa: E402
import depths  # noqa: E402

FLOOR = 0.65
CONNECTED_FLOOR = 0.80
EXCERPTS_PER_AREA = 10
BOXES_PER_AREA = 150
SMALL_FILE = 2   # a file defining this many public names or fewer: its file box is its symbol box
# How deep a map goes is chosen when it starts: the depths are data (depths.json, plus any a machine or
# a map defines; see depths.py), and every function below takes a depth's name or its full level.
DEFAULT_LEVEL = "standard"
SKIP_DIRS = VENDORED | {"test", "tests", "__tests__", "spec", "specs", "testdata", "fixtures", "docs", "doc",
                        "examples", "example", "migrations", "e2e"}
TEST_FILE = re.compile(r"(^test_.*\.py$|_test\.\w+$|\.(test|spec)\.\w+$|Tests?\.\w+$|_spec\.rb$)")
# generated code is not what a map explains: by its name, its folder, or the marker in its first lines
GENERATED_DIRS = {"generated", "__generated__"}
GENERATED_FILE = re.compile(r"([._-]generated\.\w+$|\.d\.ts$|\.pb\.go$|_pb2(_grpc)?\.py$|\.g\.dart$|\.freezed\.dart$)")
GENERATED_MARK = re.compile(r"@generated|do not edit|auto-?generated|code generated by|this file (is|was) generated", re.I)

EXPORTS = {
    ("js", "jsx", "ts", "tsx", "mjs", "cjs"): re.compile(
        r"^export\s+(?:default\s+)?(?:declare\s+)?(?:async\s+)?(?:abstract\s+)?"
        r"(?:function\*?|class|const|let|var|enum)\s+([A-Za-z_$][\w$]*)", re.M),   # not types: they shape data
    # top-level functions and types, and Type.Method for the exported methods of exported types
    ("go",): re.compile(r"^(?:func|type)\s+([A-Z]\w*)|^func\s+\(\s*\w*\s*\*?\s*([A-Z]\w*)[^)]*\)\s*([A-Z]\w*)", re.M),
    ("rs",): re.compile(r"^pub\s+(?:async\s+)?(?:fn|struct|enum|trait|type)\s+(\w+)", re.M),
    ("java", "cs"): re.compile(
        r"^public\s+(?:(?:static|final|abstract|sealed|partial)\s+)*(?:class|interface|enum|record|struct)\s+(\w+)", re.M),
    ("kt", "kts"): re.compile(
        r"^(?!private|internal)(?:(?:public|data|sealed|abstract|open|enum)\s+)*(?:class|interface|object|fun)\s+(\w+)", re.M),
    ("swift",): re.compile(r"^(?:public|open)\s+(?:final\s+)?(?:class|struct|enum|protocol|func)\s+(\w+)", re.M),
    ("rb",): re.compile(r"^(?:class|module)\s+([A-Z]\w*)", re.M),
}


def python_defs(text):
    try:
        body = ast.parse(text).body
    except (SyntaxError, ValueError):
        return []
    out = []
    for n in body:
        if isinstance(n, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_"):
            out.append(n.name)
            if isinstance(n, ast.ClassDef):
                out += [f"{n.name}.{m.name}" for m in n.body
                        if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and not m.name.startswith("_")]
    return out


def regex_defs(rx, text):
    out = []
    for m in rx.finditer(text):
        groups = [g for g in m.groups() if g]
        out.append(".".join(groups) if len(groups) == 2 else groups[0])
    return out


def public_defs(checkout):
    """{path: [names]} for every code file outside tests, docs, examples and vendored folders; a method
    is "Class.method"."""
    out = {}
    for d, dirs, fs in os.walk(checkout):
        dirs[:] = sorted(x for x in dirs if not x.startswith(".") and x not in SKIP_DIRS | GENERATED_DIRS)
        for f in sorted(fs):
            ext = f.rsplit(".", 1)[-1].lower() if "." in f else ""
            if TEST_FILE.search(f) or GENERATED_FILE.search(f):
                continue
            rx = next((r for exts, r in EXPORTS.items() if ext in exts), None)
            if ext != "py" and not rx:
                continue
            with open(os.path.join(d, f), encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            if GENERATED_MARK.search(text[:1500]):
                continue
            names = list(dict.fromkeys(python_defs(text) if ext == "py" else regex_defs(rx, text)))
            if names:
                out[os.path.relpath(os.path.join(d, f), checkout).replace(os.sep, "/")] = names
    return out


def boxed(ids):
    """{path: set of symbol names} from the map's f:<path>#<symbol> ids: each symbol as written, and the
    first part of it, so a box for Class.method also counts for Class."""
    out = {}
    for i in ids:
        if i.startswith("f:") and "#" in i:
            path, sym = i[2:].split("#", 1)
            have = out.setdefault(path, set())
            have.add(sym)
            have.add(re.split(r"[.#:(\s/]", sym)[0])
    return out


def has_box(name, have):
    if "." not in name:
        return name in have
    cls, member = name.split(".", 1)
    return name in have or member in have   # a method's box may leave its class out of the id


def code_areas(map_dir):
    try:
        areas = json.load(open(os.path.join(map_dir, "areas.json")))["areas"].values()
        return max(1, sum(1 for a in areas if a.get("kind", "code") == "code"))
    except (OSError, ValueError, KeyError):
        return 1


def as_level(level):
    return level if isinstance(level, dict) else depths.resolve(level)


def map_level(map_dir):
    """The map's depth as a full level: "depth" in its topo.config.json (a name, or a depth of its own),
    else standard."""
    try:
        with open(os.path.join(map_dir, "topo.config.json")) as f:
            value = json.load(f).get("depth")
    except (OSError, ValueError):
        value = None
    try:
        return depths.resolve(value)
    except depths.DepthError as e:
        sys.exit(f"depthcheck: {map_dir}/topo.config.json: {e}")


def full_depth(total, areas, level=DEFAULT_LEVEL):
    """Whether the map as a whole must box most of every public definition: by the depth's
    every_definition, where when_it_fits means they fit in half the boxes the map's areas hold."""
    rule = as_level(level)["every_definition"]
    return rule == "always" or (rule == "when_it_fits" and total <= areas * BOXES_PER_AREA // 2)


def area_owners(map_dir):
    """[(area, [owned path prefixes], [excluded prefixes])] for the code areas in areas.json; one area
    owning everything when there is no areas file."""
    try:
        areas = json.load(open(os.path.join(map_dir, "areas.json")))["areas"]
    except (OSError, ValueError, KeyError):
        return [("(map)", [""], [])]
    return [(name, a.get("own", []), a.get("exclude", [])) for name, a in areas.items()
            if a.get("kind", "code") == "code"]


def owned(path, own, exclude):
    return any(path == o or path.startswith(o) for o in own) and not any(path.startswith(x) for x in exclude)


def symbols_needed(defs, level=DEFAULT_LEVEL):
    """The symbol boxes an area needs at a depth: its share of the area's public definitions, counting
    at most its cap of them (standard: 65%, at most 75; deep: 65% of all; overview: none)."""
    rule = as_level(level)
    counted = defs if rule["cap"] is None else min(defs, rule["cap"])
    return math.ceil(rule["symbols"] * counted)


def check(map_dir, checkout, level=None):
    level = as_level(level) if level else map_level(map_dir)
    data = json.load(open(os.path.join(map_dir, "topo-data.json")))
    ids = [n["id"] for n in data["nodes"]]
    have = boxed(ids)
    defs = public_defs(checkout)
    # a file that defines one or two public names (a component per file, say) is mapped at symbol level
    # by its own file box
    file_boxes = {i[2:] for i in ids if i.startswith("f:") and "#" not in i}
    small = {p for p, names in defs.items() if len(names) <= SMALL_FILE and p in file_boxes}
    missing = {p: [n for n in names if not has_box(n, have.get(p, set()))] for p, names in defs.items()
               if p not in small}
    missing = {p: m for p, m in missing.items() if m}
    total = sum(len(v) for v in defs.values())
    areas = code_areas(map_dir)
    ends = set()
    for e in data["edges"]:
        ends.add(e.get("from") or e.get("source"))
        ends.add(e.get("to") or e.get("target"))
    symbols = [i for i in ids if i.startswith("f:") and "#" in i]
    per_area = []
    for name, own, exclude in area_owners(map_dir):
        d = sum(len(v) for p, v in defs.items() if owned(p, own, exclude))
        got = sum(1 for i in symbols if owned(i[2:].split("#", 1)[0], own, exclude))
        got += sum(1 for p in small if owned(p, own, exclude) and p not in have)
        per_area.append((name, got, symbols_needed(d, level), d))
    unlined = [n["id"] for n in data["nodes"] if n["id"].startswith("f:") and "#" in n["id"]
               and not re.search(r":\d+", (n.get("paths") or [""])[0])]
    # at overview a map may stop at files, so its file boxes count toward the connection floor too
    # an overview may stop at files, so there the file boxes are what must be connected
    by_file = level["connect"] == "files"
    measured = [i for i in ids if i.startswith("f:") and "#" not in i] if by_file else symbols
    if by_file:
        # a file box counts as connected when it, or a box inside it, has a connection
        kids = {}
        for nd in data["nodes"]:
            kids.setdefault(nd.get("parent"), []).append(nd["id"])
        def reaches(i, seen=()):
            return i in ends or any(reaches(k, seen + (i,)) for k in kids.get(i, []) if k not in seen)
        symbol_ends = {e.split("#", 1)[0] for e in ends if e and e.startswith("f:") and "#" in e}
        ends |= {i for i in measured if i in symbol_ends or reaches(i)}   # f:<path> owns f:<path>#<symbol>
    return {"level": level, "per_area": per_area, "unlined": unlined,
            "covered": total - sum(len(v) for v in missing.values()), "total": total,
            "full": full_depth(total, areas, level), "missing": missing,
            "symbols": len(symbols), "measured": len(measured), "lone": [s for s in measured if s not in ends],
            "excerpts": sum(1 for n in data["nodes"] if n.get("code")),
            "excerpts_needed": min(level["excerpts"] * areas, len(symbols))}


def report(map_dir, checkout, limit=20):
    """Print the report; return (passed, the check's numbers)."""
    c = check(map_dir, checkout)
    ok = True
    lv = c["level"]
    print(f"depth: {lv['name']} ({depths.floors(lv)})")
    if c["total"]:
        share = c["covered"] / c["total"]
        print(f"public definitions with a box: {c['covered']}/{c['total']} ({share:.0%}); "
              + (f"at least {lv['symbols']:.0%} must have one"
                 + (" (the map can hold them all)" if lv["every_definition"] == "when_it_fits" else "")
                 if c["full"] else "map the ones that carry the logic" if lv["symbols"]
                 else "this depth boxes the entry points and the main mechanisms only"))
        for path, names in sorted(c["missing"].items(), key=lambda kv: -len(kv[1]))[:limit]:
            print(f"  {path}: {', '.join(names[:10])}{' ...' if len(names) > 10 else ''}")
        ok = not c["full"] or share >= lv["symbols"]
    else:
        print("public definitions: none found in a language this check reads")
    for name, got, need, d in c["per_area"]:
        if d and need:
            print(f"symbol boxes in {name}: {got} (at least {need}, for {d} public definitions)")
            ok = ok and got >= need
    if c["unlined"]:
        print(f"symbol boxes that cite no line: {len(c['unlined'])} (every one must, as path:line)")
        for s in c["unlined"][:limit]:
            print(f"  no line: {s}")
        ok = False
    if c["measured"]:
        connected = 1 - len(c["lone"]) / c["measured"]
        what = "file boxes (or a box inside them)" if lv["connect"] == "files" else "symbol boxes"
        print(f"{what} with a connection: {c['measured'] - len(c['lone'])}/{c['measured']} ({connected:.0%}; "
              f"at least {CONNECTED_FLOOR:.0%})")
        for s in c["lone"][:limit]:
            print(f"  no connection: {s}")
        ok = ok and connected >= CONNECTED_FLOOR
    print(f"code excerpts: {c['excerpts']} (at least {c['excerpts_needed']})")
    ok = ok and c["excerpts"] >= c["excerpts_needed"]
    return ok, c


def main():
    ap = argparse.ArgumentParser(usage=__doc__)
    ap.add_argument("map_dir")
    ap.add_argument("--repo", help="the checkout (default MAP_DIR/checkout)")
    ap.add_argument("--limit", type=int, default=20)
    a = ap.parse_args()
    repo = a.repo or os.path.join(a.map_dir, "checkout")
    if not os.path.isdir(repo):
        sys.exit(f"depthcheck: no checkout at {repo}; pass --repo")
    ok, _ = report(a.map_dir, repo, a.limit)
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
